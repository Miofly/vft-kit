#!/bin/zsh
# Build a clickable launcher app that runs a second copy of an Electron app on its own user-data-dir
# (for example to log in a second account). The launcher brings an already running copy to the front
# instead of starting another process: two processes on one user-data-dir corrupt its LevelDB.
#
# usage: make-launcher.sh <source .app> [number=2] [output dir=/Applications]
#   DUAL_DATA_DIR overrides the data dir (default ~/Library/Application Support/<app name lowercased>-<number>).
#   DUAL_HIDE_DOCK=1 also hides the copy's Dock icon: it starts with --inspect on 127.0.0.1, dock-hide.mjs calls
#   app.dock.hide() and closes the inspector right away (needs node and the EnableNodeCliInspectArguments fuse).
# Does not start the app. Prints the launcher path, data dir and terminal command.
set -euo pipefail

src=${1:?usage: make-launcher.sh <source .app> [number] [output dir]}
num=${2:-2}
outdir=${3:-/Applications}
src=${src%/}
[[ -d $src/Contents/Frameworks/Electron\ Framework.framework ]] || {
  print -u2 "not an Electron app (no Electron Framework.framework): $src"; exit 2; }

plist=$src/Contents/Info.plist
exe=$(plutil -extract CFBundleExecutable raw "$plist")
name=$(plutil -extract CFBundleName raw "$plist" 2>/dev/null || basename "$src" .app)
icon=$(plutil -extract CFBundleIconFile raw "$plist" 2>/dev/null || true)
[[ -n $icon && $icon != *.icns ]] && icon=$icon.icns
data=${DUAL_DATA_DIR:-$HOME/Library/Application Support/${name:l}-$num}
app=$outdir/$name$num.app
hide=${DUAL_HIDE_DOCK:-0}
node_bin=
if [[ $hide == 1 ]]; then
  node_bin=$(PATH="$HOME/.volta/bin:/opt/homebrew/bin:/usr/local/bin:$PATH" command -v node) || {
    print -u2 "DUAL_HIDE_DOCK=1 needs node on PATH"; exit 2; }
fi

[[ -e $app ]] && { print -u2 "already exists, remove it first: $app"; exit 3; }

osacompile -o "$app" -e 'do shell script "/bin/zsh " & quoted form of (POSIX path of (path to me) & "Contents/Resources/launch.sh")'
res=$app/Contents/Resources
cat > "$res/launch.sh" <<EOF
#!/bin/zsh
# Generated by soft-ops make-launcher.sh: $name on its own data dir; reuse a running copy, never start a second one.
data=${(qq)data}
# Command line must start with the app binary (a shell or grep that merely mentions it must not count) and carry this
# data dir anywhere after it (--inspect may come first).
pid=\$(ps -axo pid=,command= | awk -v b=${(qq)src}"/Contents/MacOS/$exe " -v d="--user-data-dir=\$data" '{p=\$1; sub(/^ *[0-9]+ /, ""); if (index(\$0, b) == 1 && index(\$0, d)) { print p; exit }}')
if [[ -n \$pid ]]; then
  osascript -e "tell application \"System Events\" to set frontmost of (first process whose unix id is \$pid) to true" 2>/dev/null || true
elif [[ $hide == 1 ]]; then
  port=\$(( 9400 + RANDOM % 500 ))
  open -n -a ${(qq)src} --args --inspect=127.0.0.1:\$port --user-data-dir="\$data"
  ${(qq)node_bin} "\${0:h}/dock-hide.mjs" \$port >/dev/null 2>&1 &
else
  open -n -a ${(qq)src} --args --user-data-dir="\$data"
fi
EOF
chmod +x "$res/launch.sh"
[[ $hide == 1 ]] && cp "${0:A:h}/dock-hide.mjs" "$res/dock-hide.mjs"

# osacompile's Assets.car / CFBundleIconName would win over applet.icns.
rm -f "$res/Assets.car"
plutil -remove CFBundleIconName "$app/Contents/Info.plist" 2>/dev/null || true
[[ -n $icon && -f $src/Contents/Resources/$icon ]] && cp "$src/Contents/Resources/$icon" "$res/applet.icns"
plutil -replace CFBundleName -string "$name$num" "$app/Contents/Info.plist"
plutil -replace CFBundleIdentifier -string "local.${name:l}$num.launcher" "$app/Contents/Info.plist"
plutil -replace LSUIElement -bool true "$app/Contents/Info.plist"
codesign --force --deep -s - "$app" >/dev/null 2>&1
codesign -v "$app"
zsh -n "$res/launch.sh"
touch "$app"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$app"

print "launcher: $app"
print "data dir: $data"
print "terminal: open -a ${(q)app}"
