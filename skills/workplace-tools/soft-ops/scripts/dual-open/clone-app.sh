#!/bin/zsh
# Clone an Electron app into a second, fully separate app: its own bundle id, Dock icon, Cmd+Tab entry and quit, and
# its own HOME, so apps that ignore --user-data-dir or build every path from homedir() still keep each copy's login
# apart. Use make-launcher.sh instead when the app honours --user-data-dir and one Dock entry is fine.
#
# usage: clone-app.sh <source .app> [number=2] [output dir=/Applications]
#   DUAL_HOME         private HOME (default ~/Library/Application Support/<app name lowercased, spaces to ->-<number>/home)
#   DUAL_REPLACE=1    rebuild an existing copy (after the source app updates, or to change its options); refuses while it runs
#   DUAL_EGO_PROFILE  ego lite profile id (e.g. "Profile 1"): web pages the copy opens through shell.openExternal go to
#                     an ego task space on that profile instead of the default browser, so a web sign-in lands on the
#                     account that profile holds, not on the first copy's. Needs node, ego-browser and the inspect fuse.
# Does not start the copy. Redo after the source app updates (the copy's own auto-update may also undo the renames).
set -euo pipefail

src=${1:?usage: clone-app.sh <source .app> [number] [output dir]}
num=${2:-2}
outdir=${3:-/Applications}
src=${src%/}
[[ -d $src/Contents/Frameworks/Electron\ Framework.framework ]] || {
  print -u2 "not an Electron app (no Electron Framework.framework): $src"; exit 2; }

plist=$src/Contents/Info.plist
exe=$(plutil -extract CFBundleExecutable raw "$plist")
name=$(plutil -extract CFBundleName raw "$plist" 2>/dev/null || basename "$src" .app)
id=$(plutil -extract CFBundleIdentifier raw "$plist")
new=$name$num
newid=$id$num
newexe=${new// /}
home=${DUAL_HOME:-$HOME/Library/Application Support/${${name:l}// /-}-$num/home}
ego=${DUAL_EGO_PROFILE:-}
app=$outdir/$new.app
node_bin= ego_bin=
if [[ -n $ego ]]; then
  node_bin=$(PATH="$HOME/.volta/bin:/opt/homebrew/bin:/usr/local/bin:$PATH" command -v node) || {
    print -u2 "DUAL_EGO_PROFILE needs node on PATH"; exit 2; }
  ego_bin=$(command -v ego-browser) || { print -u2 "DUAL_EGO_PROFILE needs ego-browser on PATH"; exit 2; }
fi
[[ $newexe != "$exe" ]] || { print -u2 "new executable name equals the original: $exe"; exit 2; }
lsreg=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
if [[ -e $app ]]; then
  [[ ${DUAL_REPLACE:-0} == 1 ]] || { print -u2 "already exists (DUAL_REPLACE=1 rebuilds it; the data in HOME stays): $app"; exit 3; }
  # The bundle holds no user data (that is in HOME), but never swap it under a running copy.
  pgrep -f "^$app/Contents/" >/dev/null && { print -u2 "copy is running, quit it first: $app"; exit 4; }
  $lsreg -u "$app"
  rm -rf "$app"
fi

cp -cR "$src" "$app"  # APFS clone: no extra disk space
p=$app/Contents/Info.plist
plutil -replace CFBundleIdentifier -string "$newid" "$p"
plutil -replace CFBundleName -string "$new" "$p"
plutil -replace CFBundleDisplayName -string "$new" "$p"
plutil -replace CFBundleExecutable -string "$newexe" "$p"

# Electron finds its helpers by "<CFBundleName> Helper (<kind>).app", so every helper is renamed with the app.
for h in "$app/Contents/Frameworks/$name Helper"*.app(N); do
  hn=${${h:t:r}/#$name/$new}
  hp=$h/Contents/Info.plist
  mv "$h/Contents/MacOS/${h:t:r}" "$h/Contents/MacOS/$hn"
  plutil -replace CFBundleExecutable -string "$hn" "$hp"
  plutil -replace CFBundleName -string "$hn" "$hp"
  plutil -replace CFBundleIdentifier -string "${$(plutil -extract CFBundleIdentifier raw "$hp")/#$id/$newid}" "$hp"
  mv "$h" "${h:h}/$hn.app"
done

res=$app/Contents/Resources
w=$app/Contents/MacOS/$newexe
cat > "$w" <<EOF
#!/bin/zsh
# Generated by soft-ops clone-app.sh: $new runs $name's binary under a private HOME.
home=${(qq)home}
mkdir -p "\$home/Library/Caches" "\$home/Library/Application Support" "\$home/Library/Preferences" "\$home/Documents"
real_home=\$HOME
export HOME="\$home"
EOF
if [[ -n $ego ]]; then
  cp "${0:A:h}/ego-external.mjs" "$res/ego-external.mjs"
  cat >> "$w" <<EOF
port=\$(( 9400 + RANDOM % 500 ))
HOME=\$real_home ${(qq)node_bin} "\${0:A:h}/../Resources/ego-external.mjs" \$port ${(qq)ego_bin} ${(qq)ego} ${(qq)new} >/dev/null 2>&1 &
exec "\${0:A:h}/$exe" --inspect=127.0.0.1:\$port "\$@"
EOF
else
  print "exec \"\${0:A:h}/$exe\" \"\$@\"" >> "$w"
fi
chmod +x "$w"
zsh -n "$w"

codesign --force --deep -s - "$app" >/dev/null 2>&1
codesign -v "$app"
touch "$app"
$lsreg -f "$app"

print "app: $app"
print "bundle id: $newid"
print "home: $home"
[[ -n $ego ]] && print "ego profile: $ego"
print "open: open -a ${(q)app}"
